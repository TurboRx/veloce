#!/usr/bin/env bash
# Generates the nginx config and systemd unit from deploy/config.env.
# Commit the result and apply it with deploy/server.sh.
set -euo pipefail

DEPLOY="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$DEPLOY/config.env"

if ((CLUSTER_COUNT < 1 || 10000 % CLUSTER_COUNT != 0)); then
  echo "CLUSTER_COUNT must divide 10000 (1, 2, 4, 5, 8, 10, ...), got $CLUSTER_COUNT." >&2
  exit 1
fi

share=$((10000 / CLUSTER_COUNT))
upstreams=""
shares=""
clusters=""
for ((i = 0; i < CLUSTER_COUNT; i++)); do
  upstreams+="upstream veloce_cluster_$i { server 127.0.0.1:$((SERVICE_BASE_PORT + i)); }"$'\n'
  if ((i < CLUSTER_COUNT - 1)); then
    if ((share % 100 == 0)); then
      shares+="        $((share / 100))% \"$i\";"$'\n'
    else
      shares+="$(printf '        %d.%02d%% "%d";' $((share / 100)) $((share % 100)) "$i")"$'\n'
    fi
  else
    shares+="        * \"$i\";"$'\n'
  fi
  clusters+="        \"$i\" veloce_cluster_$i;"$'\n'
done

render() {
  local out="$1"
  out="${out//@CLUSTER_COUNT@/$CLUSTER_COUNT}"
  out="${out//@SERVICE_BASE_PORT@/$SERVICE_BASE_PORT}"
  out="${out//@SERVICE_DIR@/$SERVICE_DIR}"
  out="${out//@WEB_DOMAIN@/$WEB_DOMAIN}"
  out="${out//@API_DOMAIN@/$API_DOMAIN}"
  out="${out//@WEB_DIR@/$WEB_DIR}"
  out="${out//@API_MAX_BODY_SIZE@/$API_MAX_BODY_SIZE}"
  out="${out//@UPSTREAMS@/${upstreams%$'\n'}}"
  out="${out//@SHARES@/${shares%$'\n'}}"
  out="${out//@CLUSTERS@/${clusters%$'\n'}}"
  printf '%s\n' "$out"
}

read -r -d '' nginx_template <<'EOF' || true
# Generated by deploy/generate.sh from deploy/config.env, don't edit.
#
# nginx config for @WEB_DOMAIN@ and @API_DOMAIN@, included inside
# the http block. All traffic arrives through the Cloudflare tunnel, which
# connects from localhost.

# Use client IP from Cloudflare tunnel
set_real_ip_from 127.0.0.1;
set_real_ip_from ::1;
real_ip_header CF-Connecting-IP;

# Rate limits per client IP
map $request_method $veloce_api_write_key {
    default $binary_remote_addr;
    GET     "";
    HEAD    "";
    OPTIONS "";
}

limit_req_zone $binary_remote_addr zone=veloce_api:64m rate=15r/s;
limit_req_zone $veloce_api_write_key zone=veloce_api_write:64m rate=5r/s;
limit_req_zone $binary_remote_addr zone=veloce_webhook:16m rate=30r/s;

limit_req_status 429;

# Upstreams for service clusters
@UPSTREAMS@

map $uri $veloce_app_id {
    ~^/v1/apps/(?<id>[^/]+)/ $id;
    default "";
}

split_clients "${veloce_app_id}" $veloce_cluster {
@SHARES@
}

map $veloce_cluster $veloce_upstream {
    default veloce_cluster_0;
@CLUSTERS@
}

map $http_upgrade $veloce_connection_upgrade {
    default upgrade;
    ""      "";
}

server {
    listen 127.0.0.1:80 default_server;
    server_name @API_DOMAIN@;

    proxy_http_version 1.1;
    proxy_set_header Upgrade $http_upgrade;
    proxy_set_header Connection $veloce_connection_upgrade;
    proxy_set_header Host $host;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Host $host;
    proxy_set_header X-Real-IP $remote_addr;

    client_max_body_size @API_MAX_BODY_SIZE@;
    proxy_connect_timeout 60s;
    proxy_read_timeout 60s;
    proxy_send_timeout 60s;
    send_timeout 60s;

    location / {
        limit_req zone=veloce_api burst=50 delay=10;
        limit_req zone=veloce_api_write burst=10;

        proxy_pass http://$veloce_upstream;
    }

    location /v1/webhooks/ {
        limit_req zone=veloce_webhook burst=100 nodelay;

        proxy_pass http://$veloce_upstream;
    }
}

server {
    listen 127.0.0.1:80;
    server_name www.@WEB_DOMAIN@;

    return 308 https://@WEB_DOMAIN@$request_uri;
}

server {
    listen 127.0.0.1:80;
    server_name @WEB_DOMAIN@;

    root @WEB_DIR@;
    absolute_redirect off;

    rewrite ^/(.+)/$ /$1 permanent;

    location /_next/static/ {
        add_header Cache-Control "public, max-age=31536000, immutable";
    }

    location ~ ^/apps/[^/]+/?$ {
        try_files "/apps.html" =404;
    }

    location ~ ^/builder/?$ {
        try_files "/builder.html" =404;
    }

    location / {
        try_files $uri $uri.html $uri/ =404;
    }

    error_page 404 /404.html;
}
EOF
render "$nginx_template" >"$DEPLOY/nginx.conf"

read -r -d '' unit_template <<'EOF' || true
# Generated by deploy/generate.sh from deploy/config.env, don't edit.
#
# Service cluster %i of @CLUSTER_COUNT@, run as veloce-service@0 to veloce-service@N.
# Reads veloce.toml from @SERVICE_DIR@ and applies migrations on every start.
[Unit]
Description=Veloce cluster %i
After=network-online.target postgresql.service
Wants=network-online.target
StartLimitIntervalSec=0

[Service]
WorkingDirectory=@SERVICE_DIR@
ExecStartPre=@SERVICE_DIR@/veloce database migrate up
ExecStart=/bin/sh -c 'exec @SERVICE_DIR@/veloce server'
Restart=always
RestartSec=5

[Install]
WantedBy=multi-user.target
EOF
render "$unit_template" >"$DEPLOY/veloce-service@.service"

echo "Generated deploy/nginx.conf and deploy/veloce-service@.service for $CLUSTER_COUNT cluster(s)."
